class Command(BaseCommand):
    help = 'Seeds canonical 45 Shinobi records into SQLite/PostgreSQL from embedded canonical dataset'

    def add_arguments(self, parser):
        parser.add_argument(
            '--overwrite',
            action='store_true',
            help='Synchronize and overwrite existing database records with canonical dataset'
        )

    def handle(self, *args, **options):
        overwrite = options.get('overwrite', False)

        # Integrity validation
        if len(CANONICAL_SHINOBI) != 45:
            self.stderr.write(self.style.ERROR(f"Expected 45 canonical records, found {len(CANONICAL_SHINOBI)}!"))
            raise ValueError(f"Expected 45 canonical records, found {len(CANONICAL_SHINOBI)}")

        ids = [r['id'] for r in CANONICAL_SHINOBI]
        if len(set(ids)) != 45:
            self.stderr.write(self.style.ERROR("Duplicate IDs detected in canonical records!"))
            raise ValueError("Duplicate IDs detected in canonical records")

        created_count = 0
        updated_count = 0
        unchanged_count = 0

        fields = [
            'name', 'kanji', 'village', 'villageDisplay', 'clan', 'clanDisplay',
            'rank', 'rankDisplay', 'status', 'image', 'specialty', 'natures',
            'classification', 'summary', 'techniques'
        ]

        for r in CANONICAL_SHINOBI:
            shinobi = Shinobi.objects.filter(id=r['id']).first()
            if not shinobi:
                Shinobi.objects.create(
                    id=r['id'],
                    name=r.get('name', ''),
                    kanji=r.get('kanji', ''),
                    village=r.get('village', ''),
                    villageDisplay=r.get('villageDisplay', ''),
                    clan=r.get('clan', ''),
                    clanDisplay=r.get('clanDisplay', ''),
                    rank=r.get('rank', ''),
                    rankDisplay=r.get('rankDisplay', ''),
                    status=r.get('status', ''),
                    image=r.get('image', ''),
                    specialty=r.get('specialty', ''),
                    natures=r.get('natures', ''),
                    classification=r.get('classification', ''),
                    summary=r.get('summary', ''),
                    techniques=r.get('techniques', []),
                )
                created_count += 1
            else:
                if overwrite:
                    changed = False
                    for f in fields:
                        if getattr(shinobi, f) != r.get(f):
                            setattr(shinobi, f, r.get(f))
                            changed = True

                    if changed:
                        shinobi.save()
                        updated_count += 1
                    else:
                        unchanged_count += 1
                else:
                    unchanged_count += 1

        total = Shinobi.objects.count()

        self.stdout.write(self.style.SUCCESS(
            f"Created: {created_count} | Updated: {updated_count} | Unchanged: {unchanged_count} | Total: {total}"
        ))
